package com.callanswer.core.model

enum class Language { HI, EN }

enum class VoiceGender { MALE, FEMALE }

enum class IntentCategory { DELIVERY, DOOR_NOT_OPENED, SOLICITATION, UNKNOWN }

enum class NetworkQuality { AVAILABLE, DEGRADED, UNAVAILABLE }

/** LIVE = User and/or Caller during Take_Over. */
enum class Speaker { CALLER, AGENT, USER, LIVE }

enum class Outcome {
    DELIVERY_DIRECTIONS_GIVEN, TRANSFERRED, TRANSFER_FAILED, STALLED, UNKNOWN_CALLBACK,
    CALLER_SILENT, TAKEN_OVER, USER_ENDED, CALLER_HUNG_UP, INTERRUPTED, ERROR, ABUSIVE_CALLER,
}

enum class EndReason {
    CALLER_HUNG_UP, USER_ENDED, CALLER_SILENCE, MAX_DURATION, UNKNOWN_AFTER_CLARIFY,
    REPEATS_EXHAUSTED, DELIVERY_DONE, AUDIO_INTERRUPTED, RESPONSE_FAILURE, TRANSFERRED_CALL_ENDED,
    /** The Caller used abusive language; the Agent said so and hung up. */
    ABUSIVE_LANGUAGE,
}

enum class RecordingStatus { PENDING, LINKED, NOT_FOUND, NO_FOLDER_SELECTED, DELETED, FOLDER_ACCESS_LOST }

enum class ReportStatus {
    NOT_REPORTED, PREPARED, HANDED_TO_MESSAGING_APP, SENT, FAILED, CANNOT_REPORT_NUMBER_UNAVAILABLE,
}

enum class TransferPath { PATH_A_MERGE, PATH_B_ALERT }

enum class AlertReason { PATH_A_UNAVAILABLE, TARGET_NOT_CONFIGURED, NO_ANSWER_30S, FAILED_THEN_ALERT }

enum class TransferOutcome { MERGED, TAKEN_OVER_BY_USER, NO_TAKEOVER_30S, CALL_ENDED_WHILE_WAITING }

/** Notes written to the Call_Log (failures and notable events). */
enum class LogNoteKind {
    TRANSFER_FAILED,
    TRANSFER_COMPLETED_BY_USER,
    TIME_READ_FAILED,
    MAP_SMS_FAILED,
    MAP_LOCATION_MISSING,
    TRANSFER_TARGET_MISSING,
    PROCESSING_ERROR,
    SPEECH_SYNTHESIS_FAILED,
    STALLING_REPLY_FAILED,
    CALLER_SILENT,
    NO_SEND_RESULT,
}

/** Kinds of User notifications requested by the engine and the app. */
enum class NotificationKind {
    MAP_LOCATION_MISSING,
    MAP_SMS_FAILED,
    TRANSFER_STARTED,
    TRANSFER_FAILED,
    TRANSFER_TARGET_MISSING,
    SILENT_CALLER,
    UNKNOWN_CALLER_INTENT,
    CALL_NOT_LOGGED,
    SPAM_CALL_SCREENED,
}
